// Generates TypeScript and C++ sources from the JSON files in schema/.
// Output is committed, so consumers (console, bridge) never need Node to build.
// Usage: npm run generate
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const write = (p, text) => {
  const full = join(root, p);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, text);
  console.log('wrote', p);
};
const HEADER = 'AUTO-GENERATED by scripts/generate.mjs from schema/. Do not edit by hand.';

const { protocolVersion, extraSlots, controls } = read('schema/controls.json');
const messages = read('schema/messages.schema.json');

// Sanity checks: unique ids, sane ranges, default inside range.
const seen = new Set();
for (const c of controls) {
  if (seen.has(c.id)) throw new Error(`duplicate control id ${c.id}`);
  seen.add(c.id);
  if (!(c.min < c.max)) throw new Error(`${c.id}: min must be < max`);
  if (c.default < c.min || c.default > c.max) throw new Error(`${c.id}: default outside range`);
  if (c.scale === 'log' && c.min <= 0) throw new Error(`${c.id}: log scale needs min > 0`);
}

const messageTypes = Object.values(messages.$defs)
  .map((d) => d.properties?.type?.const)
  .filter(Boolean);

// ---------- TypeScript ----------
const tsControls = `// ${HEADER}
export const PROTOCOL_VERSION = ${protocolVersion} as const;
/** Automatable slots the bridge reserves for plugin-specific controls (a profile's 'extras'). */
export const EXTRA_SLOTS = ${extraSlots} as const;

export type ControlKind = 'continuous' | 'switch';
export type ControlScale = 'linear' | 'log' | 'fader';
export type ControlSection = 'input' | 'filter' | 'eq' | 'dyn' | 'output';

export interface ControlDef {
  readonly id: string;
  readonly section: ControlSection;
  readonly group: string;
  readonly label: string;
  readonly kind: ControlKind;
  readonly scale: ControlScale;
  readonly min: number;
  readonly max: number;
  readonly default: number;
  readonly step: number;
  readonly unit: string;
}

export const CONTROLS = ${JSON.stringify(controls, null, 2)} as const satisfies readonly ControlDef[];

export type ControlId = (typeof CONTROLS)[number]['id'];

export const CONTROL_BY_ID: Readonly<Record<ControlId, ControlDef>> = Object.fromEntries(
  CONTROLS.map((c) => [c.id, c]),
) as Record<ControlId, ControlDef>;

export const MESSAGE_TYPES = ${JSON.stringify(messageTypes)} as const;
export type MessageType = (typeof MESSAGE_TYPES)[number];
`;
write('generated/ts/controls.ts', tsControls);

const tsOpts = { bannerComment: `// ${HEADER}`, additionalProperties: false, strictIndexSignatures: false, ignoreMinAndMaxItems: true, style: { singleQuote: true } };
write('generated/ts/messages.ts', await compile(messages, 'StriplineMessage', { ...tsOpts, cwd: join(root, 'schema') }));
write('generated/ts/profile.ts', await compile(read('schema/profile.schema.json'), 'StriplineProfile', { ...tsOpts, cwd: join(root, 'schema') }));

// ---------- C++ ----------
const cppStr = (s) => JSON.stringify(s); // JSON string escaping is valid C++ for our ASCII-ish labels
const num = (n) => (Number.isInteger(n) ? `${n}.0f` : `${n}f`);
const kind = (k) => (k === 'switch' ? 'Kind::Switch' : 'Kind::Continuous');
const scale = (s) => ({ linear: 'Scale::Linear', log: 'Scale::Log', fader: 'Scale::Fader' })[s];
const cppControls = `// ${HEADER}
#pragma once
#include <array>
#include <string_view>

namespace stripline::protocol
{
inline constexpr int kProtocolVersion = ${protocolVersion};
inline constexpr int kDefaultPort = 9420;
inline constexpr int kExtraSlots = ${extraSlots};

enum class Kind { Continuous, Switch };
enum class Scale { Linear, Log, Fader };

struct ControlDef
{
    std::string_view id;
    std::string_view section;
    std::string_view group;
    std::string_view label;
    Kind kind;
    Scale scale;
    float min, max, defaultValue, step;
    std::string_view unit;
};

inline constexpr std::array<ControlDef, ${controls.length}> kControls {{
${controls.map((c) => `    { ${cppStr(c.id)}, ${cppStr(c.section)}, ${cppStr(c.group)}, ${cppStr(c.label)}, ${kind(c.kind)}, ${scale(c.scale)}, ${num(c.min)}, ${num(c.max)}, ${num(c.default)}, ${num(c.step)}, ${cppStr(c.unit)} },`).join('\n')}
}};

inline constexpr int indexOfControl (std::string_view id) noexcept
{
    for (size_t i = 0; i < kControls.size(); ++i)
        if (kControls[i].id == id)
            return static_cast<int> (i);
    return -1;
}

namespace msg
{
${messageTypes.map((t) => `    inline constexpr std::string_view ${t} = ${cppStr(t)};`).join('\n')}
} // namespace msg
} // namespace stripline::protocol
`;
write('generated/cpp/stripline/Controls.h', cppControls);
